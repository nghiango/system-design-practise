#!/usr/bin/env python3
"""Publish one topic's chart and image tags into the GitOps repository.

Writes only topics/<topic>/{chart/,values-local.yaml,topic.yaml}. Never writes
topics/active.yaml, charts/ or environments/.
"""
import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import List

from gitops_repo import clone, commit_and_push, validate_topic

ROOT = Path(__file__).resolve().parents[2]
REVISION_RE = re.compile(r"^[0-9a-f]{40}$")
PREFIX_RE = re.compile(r"^[a-z0-9][a-z0-9.:/_-]*$")
CHART_IGNORE = shutil.ignore_patterns("tests", "__pycache__", "*.pyc", "*.tgz")


def values_local(topic: str, image_prefix: str, revision: str) -> str:
    return (f"# Generated by Jenkins (system-design/{topic}). Never put secrets here.\n"
            f'revision: "{revision}"\n'
            f'imagePrefix: "{image_prefix}"\n'
            f'imageTag: "{revision}"\n')


def publish(gitops: Path, source_root: Path, topic: str, image_prefix: str, revision: str) -> List[str]:
    validate_topic(topic)
    source = source_root / "topics" / topic
    if not (source / "topic.yaml").is_file():
        raise ValueError(f"unknown topic {topic!r}")
    if not (source / "deploy" / "values.yaml").is_file():
        raise ValueError(f"topic {topic!r} has no deploy/values.yaml")
    if not REVISION_RE.fullmatch(revision):
        raise ValueError(f"expected a full 40-character commit SHA, got {revision!r}")
    if not PREFIX_RE.fullmatch(image_prefix):
        raise ValueError(f"invalid image prefix {image_prefix!r}")

    dest = gitops / "topics" / topic
    chart = dest / "chart"
    if chart.exists():
        shutil.rmtree(chart)
    shutil.copytree(source_root / "deploy" / "topic-chart", chart, ignore=CHART_IGNORE)
    shutil.copyfile(source / "deploy" / "values.yaml", chart / "values-topic.yaml")
    for extra in sorted((source / "deploy" / "templates").glob("*.yaml")):
        target = chart / "templates" / extra.name
        if target.exists():
            raise ValueError(f"topic template {extra.name} would overwrite a generic chart template")
        shutil.copyfile(extra, target)
    (dest / "values-local.yaml").write_text(values_local(topic, image_prefix, revision))
    shutil.copyfile(source / "topic.yaml", dest / "topic.yaml")
    return sorted(str(p.relative_to(gitops)) for p in dest.rglob("*") if p.is_file())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--topic", required=True)
    parser.add_argument("--image-prefix", required=True)
    parser.add_argument("--revision", required=True)
    parser.add_argument("--gitops-url", required=True)
    parser.add_argument("--gitops-branch", default="main")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="sd-gitops-") as tmp:
        repo = clone(args.gitops_url, args.gitops_branch, Path(tmp) / "repo")
        publish(repo, ROOT, args.topic, args.image_prefix, args.revision)
        base = repo / "topics" / args.topic
        subprocess.run(["helm", "lint", str(base / "chart"), "-f", str(base / "chart" / "values-topic.yaml"),
                        "-f", str(base / "values-local.yaml")], check=True)
        pushed = commit_and_push(repo, [f"topics/{args.topic}"],
                                 f"Deploy topic {args.topic} {args.revision} (linux/arm64)", args.gitops_branch)
        print(f"published {args.topic} {args.revision}" if pushed else f"{args.topic} already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
